const NON_SPACING_MARK = /^[\p{Mn}\p{Me}]$/u
const FIRST_WIDE_CODE_POINT = 0x1100

export function codePointWidth(codePoint: number): number {
  if (codePoint < FIRST_WIDE_CODE_POINT) {
    if (codePoint < 0x300) return 1

    return NON_SPACING_MARK.test(String.fromCodePoint(codePoint)) ? 0 : 1
  }

  let low = 0
  let high = WIDE_RANGES.length - 1

  while (low <= high) {
    const middle = (low + high) >> 1
    const range = WIDE_RANGES[middle]!

    if (codePoint < range[0]) high = middle - 1
    else if (codePoint > range[1]) low = middle + 1
    else return 2
  }

  return NON_SPACING_MARK.test(String.fromCodePoint(codePoint)) ? 0 : 1
}

export function isCombiningCodePoint(codePoint: number): boolean {
  return codePoint >= 0x300 && NON_SPACING_MARK.test(String.fromCodePoint(codePoint))
}
